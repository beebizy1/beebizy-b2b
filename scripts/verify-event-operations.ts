import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { and, eq } from "drizzle-orm";
import { db, schema as s } from "../src/server/db.ts";
import { createBizyPartner, getBizyPartnerDraft, listBizyPartners, publicBizyLink, revokeBizyPartner, saveBizyPartnerDraft, submitBizyPartner } from "../src/server/bizyLink.ts";
import { eventOperationsFinancials, getEventOperations, saveEventOperations } from "../src/server/eventOperations.ts";
import { emptyEventOperations, apparelQuestion, apparelReport } from "../src/data/eventOperations.ts";
import { normalizeRegistrationPage } from "../src/data/registrationPage.ts";
import { publicRsvpPartyQueries } from "../src/server/publicRsvpStore.ts";
import * as repos from "../src/server/repos.ts";
import type { RequestContext } from "../src/server/auth.ts";

// This script must target a separately created, named QA event. It sends no
// notifications and does not create or simulate payments.
const eventId = process.env.QA_EVENT_ID;
assert.ok(eventId, "QA_EVENT_ID is required.");
const [event] = await db.select().from(s.events).where(eq(s.events.id, eventId));
assert.ok(event?.title.startsWith("QA - Bizy Link"), "Refusing to modify a customer event.");
assert.equal((await db.select().from(s.registrations).where(eq(s.registrations.eventId, eventId))).length, 0, "Use a fresh QA event.");
const [owner] = await db.select().from(s.workspaceMembers).where(and(eq(s.workspaceMembers.workspaceId, event.workspaceId), eq(s.workspaceMembers.role, "owner"))).limit(1);
assert.ok(owner);
const ctx: RequestContext = { workspaceId: event.workspaceId, userId: owner.userId, role: "owner", email: null };
const suffix = randomBytes(5).toString("hex");
const vendorId = `qa_ops_vendor_${suffix}`; const bookingId = `qa_ops_booking_${suffix}`; const sponsorId = `qa_ops_sponsor_${suffix}`;
await db.insert(s.vendors).values({ id: vendorId, workspaceId: event.workspaceId, name: "QA Florist - Bizy Link", category: "Florist" });
await db.insert(s.eventVendors).values({ id: bookingId, eventId, workspaceId: event.workspaceId, vendorId, notes: "INTERNAL-QA-DO-NOT-EXPOSE", feeCents: 50000 });
await db.insert(s.sponsorships).values({ id: sponsorId, eventId, workspaceId: event.workspaceId, companyName: "QA Sponsor - Bizy Link", tier: "gold", status: "confirmed", amountCents: 250000 });
const shirt = apparelQuestion("shirt", `shirt_${suffix}`);
await repos.events.updateRegistrationPage(ctx, eventId, { questions: [shirt], maxAdditionalGuests: 1 });
const shared = await repos.events.share(ctx, eventId); const token = shared.shareToken;
let snapshot = await getEventOperations(ctx, eventId); const document = emptyEventOperations(); document.apparel.questionIds = [shirt.id];
snapshot = await saveEventOperations(ctx, eventId, { expectedRevision: snapshot.revision, document });
const concurrent = await Promise.allSettled(["A", "B"].map(vendorNotes => saveEventOperations(ctx, eventId, { expectedRevision: snapshot.revision, document: { ...snapshot.document, apparel: { ...snapshot.document.apparel, vendorNotes } } })));
assert.equal(concurrent.filter(result => result.status === "fulfilled").length, 1);
assert.equal(concurrent.filter(result => result.status === "rejected").length, 1);
await assert.rejects(() => getEventOperations({ ...ctx, workspaceId: `other_${suffix}` }, eventId), { status: 404 });
await assert.rejects(() => createBizyPartner(ctx, eventId, { role: "vendor", resourceId: sponsorId }), { status: 404 });
const sponsor = await createBizyPartner(ctx, eventId, { role: "sponsor", resourceId: sponsorId, seatLimit: 2 });
const access = new URL(sponsor.path, "https://test.invalid").searchParams.get("access")!;
const roster = { people: [{ firstName: "QA Alex", lastName: suffix, email: "", answers: { [shirt.id]: "M" } }, { firstName: "QA Sam", lastName: suffix, email: "", answers: { [shirt.id]: "L" } }] };
const normal = publicRsvpPartyQueries({ eventId, workspaceId: event.workspaceId, segment: "General", organization: null, partyId: `normal_${suffix}`, people: [{ name: `QA Normal ${suffix}`, email: null, fields: [], guestId: `qa_normal_${suffix}`, registrationId: `qa_normal_reg_${suffix}` }] });
const registrations = await Promise.all([submitBizyPartner(token, access, roster), submitBizyPartner(token, access, roster), db.batch(normal.map(query => db.execute(query)))]);
assert.ok(registrations[0].ok && registrations[1].ok);
assert.equal((await repos.registrations.listForEvent(ctx, eventId)).length, 3);
const sizing = apparelReport(await repos.registrations.listForEvent(ctx, eventId), normalizeRegistrationPage({ questions: [shirt] }), (await getEventOperations(ctx, eventId)).document);
assert.equal(sizing.quantities.reduce((sum, row) => sum + row.requested, 0), 2);
const capacity = await createBizyPartner(ctx, eventId, { role: "sponsor", resourceId: sponsorId, seatLimit: 2 });
const capAccess = new URL(capacity.path, "https://test.invalid").searchParams.get("access")!;
await db.update(s.events).set({ capacity: 4 }).where(eq(s.events.id, eventId));
try { await assert.rejects(() => submitBizyPartner(token, capAccess, roster), { status: 409 }); }
finally { await db.update(s.events).set({ capacity: 50 }).where(eq(s.events.id, eventId)); }
assert.equal((await repos.registrations.listForEvent(ctx, eventId)).length, 3);
await revokeBizyPartner(ctx, eventId, capacity.id);
await assert.rejects(() => publicBizyLink(token, capAccess), { status: 404 });
await assert.rejects(() => submitBizyPartner(token, capAccess, roster), { status: 404 });
const vendor = await createBizyPartner(ctx, eventId, { role: "vendor", resourceId: bookingId, seatLimit: 1 });
const vendorAccess = new URL(vendor.path, "https://test.invalid").searchParams.get("access")!;
const payload = await publicBizyLink(token, vendorAccess);
assert.equal(JSON.stringify(payload).includes("INTERNAL-QA"), false);
const expected = payload.partner!.schedule!;
const saves = await Promise.allSettled(["First vendor note", "Second vendor note"].map(notes => submitBizyPartner(token, vendorAccess, { expected, schedule: { arrivalTime: "08:00", serviceTime: "09:00", departureTime: "15:00", notes } })));
assert.equal(saves.filter(result => result.status === "fulfilled").length, 1);
assert.equal(saves.filter(result => result.status === "rejected").length, 1);
const vendorSaved = (await publicBizyLink(token, vendorAccess)).partner!.schedule!;
assert.equal(vendorSaved.arrivalTime, "08:00");
assert.ok((await listBizyPartners(ctx, eventId)).some(row => row.id === vendor.id && row.vendorNotes === vendorSaved.notes));
const [privateBooking] = await db.select().from(s.eventVendors).where(eq(s.eventVendors.id, bookingId));
assert.equal(privateBooking.notes, "INTERNAL-QA-DO-NOT-EXPOSE");
await saveBizyPartnerDraft(token, vendorAccess, { revision: Date.now(), values: { schedule: JSON.stringify(vendorSaved) }, discarded: false });
assert.equal((await getBizyPartnerDraft(token, vendorAccess))?.values.schedule, JSON.stringify(vendorSaved));
assert.equal(await getBizyPartnerDraft(token, access), null);
const master = await publicBizyLink(token);
assert.equal(master.partner, undefined);
assert.equal(JSON.stringify(master).includes(vendorAccess), false);
assert.deepEqual((await eventOperationsFinancials(ctx, eventId)).currencies, []);
const uiSponsor = await createBizyPartner(ctx, eventId, { role: "sponsor", resourceId: sponsorId, seatLimit: 3 });
writeFileSync("/private/tmp/beebizy-operations-qa.json", JSON.stringify({ eventId, vendorId, bookingId, sponsorId, token, sponsorPath: uiSponsor.path, vendorPath: vendor.path }), { mode: 0o600 });
console.log("PASS: persisted operations, stale-write fencing, cross-workspace denial, concurrent roster idempotency, normal RSVP lock order, atomic capacity rollback, revocation, vendor concurrency/private notes, draft isolation, apparel counts and financial source reads.");
console.log("Synthetic QA event retained for signed-in browser verification:", eventId);
